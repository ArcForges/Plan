    files[design / DELIVERY_REL / 'substitutes.md'] = render_substitutes(g)
    files[design / DELIVERY_REL / 'shared-resources.md'] = render_resources(g)
    files[design / DELIVERY_REL / 'schedule-analysis.md'] = render_analysis(g)
